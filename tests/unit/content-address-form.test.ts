const ENRICHMENT_DIR = "src/content/enrichment";
const PHONICS = [
  "src/content/english/phonics-emilia.json",
  "src/content/english/phonics-evelyn.json",
];

/**
 * גוף שני נקבה שאינו ציווי — עבר, הווה ועתיד.
 *
 * 🔴 **בלי `\b`.** גבול-מילה ב-JS הוא ASCII בלבד ואינו נדלק אחרי אות
 * עברית, ולכן בדיקה שנשענת עליו עוברת תמיד — כלומר מתה. זה בדיוק
 * הכשל שנתפס ב-BL-021 (14.8), והוא חזר כאן בסבב הראשון של השומר.
 * הגבולות נכתבים במפורש כמחלקות-תווים.
 */
const B_START = String.raw`(?<=^|[\s,.:;!?"״'(—–])`;
const B_END = String.raw`(?=[\s,.:;!?"״')—–]|$)`;

/**
 * ציווי בגוף שני נקבה — הצורה שהייתה במאגרים לפני הניטרול.
 * `ו` החיבור מותרת כקידומת ("ולרשום"), ולכן היא חלק מגבול-הפתיחה.
 */
const FEMININE_IMPERATIVES = new RegExp(
  `(?:${B_START}|(?<=ו))` +
    `(רשמי|שאלי|סמני|בדקי|בחרי|מצאי|חפשי|כתבי|חשבי|אמרי|בקשי|נחשי|מלאי|שפכי|מדדי|תארי|קראי|שימי|קחי|נסי|חכי|חזרי|עברי|עמדי|ציירי|צלמי|הסתכלי|הכניסי|הניחי|השווי|החליפי|הוציאי|הדליקי|האירי|הוסיפי|הקיפי|הראי|הביטי|הדביקי|קמטי|תחבי|געי|סדרי|מתחי|קבעי|שגרי|חקרי|צפי|שלחי|עצרי|הציגי|ערבבי|הדגימי|המשיכי|התחילי|פענחי|לחצי|פרקי|נערי|סגרי|העמידי|תצפי|השוואי|הכיני|החזירי|תכתבי|תגעי|תסדרי|תתני|` +
    // ציוויים קצרים — התפספסו בסבב הראשון כי הם בני 3 אותיות
    // ונבלעים בתוך מילים ("בני משפחה"). הגבולות המפורשים מגנים.
    `ראי|גלי|צאי|לכי|קומי|עני|קפצי|רוצי|הרימי|קרבי|החשיכי|החזיקי|שמרי|הסבירי|הפכי|מזגי|טפטפי|כסי|גלגלי|` +
    // גל שני — נמצא רק בסריקה שיטתית של **כל** מילה שנגמרת ב-י.
    // רשימה שנבנתה מהזיכרון פספסה 30+ צורות; הלקח: לסרוק, לא לנחש.
    `אספי|בצעי|הביאי|הזיזי|הכפילי|הסתירי|העתיקי|הצמידי|הרטיבי|הרכיבי|מייני|שחקי|טבלי|כופפי|פהקי|פזרי|פתחי|קפלי|שפשפי|תרגלי|הפעילי|הרפי|גזרי|מחקי|קשרי|נפחי|למדי|` +
    // עתיד בגוף שני נקבה — משמש כציווי רך ("אם תזיזי", "אל תגלי").
    `תגלי|תזיזי|תפתרי|תהפכי|תכתבי|תגעי|תסדרי|תתני|תנערי|` +
    // ⚠️ `חברי` דו-משמעי: גם ציווי ("חברי בחוט") וגם סמיכות
    // ("חברי הקבוצה"). הגבולות **אינם** מבחינים ביניהם — שניהם
    // מילה שלמה — ולכן הסמיכויות הנפוצות רשומות ב-`LEXICAL_EXEMPT`.
    // זו פשרה מודעת: עדיף חריג קצר וקריא מאשר להשאיר ציווי אמיתי
    // בלי הגנה. אם תיווצר סמיכות חדשה, הבדיקה תצעק ותתבקש הוספה.
    `דרגי|חברי)` +
    B_END,
);

/**
 * רבים-נקבה ויחיד-נקבה בהווה — "מגדר בתחפושת".
 *
 * הרבים ("בודקות") נראה מכליל ("אנחנו יחד") אבל מסגיר מין; זו הטעות
 * שקל ליפול בה כשמנטרלים בעברית, והיא מתועדת ב-`greetings.ts`
 * ("מתחילות לאט" עבר לרשימה המגודרת, לא לניטרלית).
 *
 * היחיד ("בודקת", "חוקרת") חמק מהסבב הראשון כי חיפשתי רק רבים —
 * שלוש שורות `activity` נשארו מגודרות עד שסקירה בעין תפסה אותן.
 */
const FEMININE_PLURAL = new RegExp(
  // ⚠️ `ו` החיבור חייבת להיות מותרת גם כאן, בדיוק כמו בציוויים.
  // בלעדיה `עוקבת ומגלה` עבר ירוק: המילה הראשונה נתפסה, השנייה —
  // שקידומת `ו` דבוקה לה — לא. אסימטריה בין שתי תבניות שאמורות
  // להיות תאומות היא בור שקשה לראות בקריאה.
  `(?:${B_START}|(?<=ו))` +
    `(בודקות|מגלות|בונות|מודדות|משוות|מחפשות|משחקות|נוגעות|מנחשות|מסמנות|יודעות|רואות|לומדות|יוצרות|חוקרות|סופרות|כותבות|מכינות|אוספות|בוחרות|מציירות|קוראות|שואלות|מנסות|עוקבות|מעבירות|מצפינות|` +
    `בודקת|מגלה|בונה|מודדת|משווה|מחפשת|משחקת|מנחשת|מסמנת|חוקרת|סופרת|כותבת|אוספת|בוחרת|מציירת|מריצה|עוקבת|מעבירה|מצפינה)` +
    B_END,
);

const FEMININE_ADDRESS = new RegExp(
  B_START +
    `(את (חושבת|רואה|יודעת|מכירה|אומרת|עושה|יכולה|בודקת|מחפשת|משתמשת|שמה|מתחילה|נוגעת|מוסיפה|עונה|מזיזה)|שאת|אותך|תוכלי|מוכנה|זוכרת|תמצאי|תצליחי|תשמעי|תראי|ניחשת|דייקת|סיימת|עשית|אכלת|הכנת|נתקעת|צדקת|כתבת|השתמשת|הגעת|סימנת)` +
    B_END,
);

/**
 * לוכסן מגדרי — אסור מפורשות (תקן gov.il: "לא נגיש לקוראי מסך").
 *
 * הצורה האסורה מדביקה **סיומת** למילה: "מוכן/ה", "יכול/ה", "תלמיד/ה".
 * לוכסן בין שתי מילים שלמות ("כן/לא") הוא פיסוק לגיטימי ואינו מגדרי,
 * ולכן הדפוס מחייב סיומת קצרה (1–2 אותיות) שאחריה גבול-מילה.
 */
const SLASH_FORM = new RegExp(String.raw`[א-ת]\/(ה|ית|ות|ים|י)` + B_END);

/**
 * חריגים אמיתיים: "ספרי בישול" הוא סמיכות ("books of"), לא ציווי,
 * ו-`parentTip` פונה **להורה** ולא לילד — פנייה להורה היא שאלה
 * נפרדת שנרשמה ל-BACKLOG ואינה בסקופ של G4.
 */
const LEXICAL_EXEMPT = [
  /ספרי בישול/,
  /ספרי "מה ולמה"/,
  // "בערך לחצי" = חצי (שם עצם), לא הציווי "לחצי על הרמקול".
  /בערך לחצי/,
  // "כן/לא" ו"שאלות של כן/לא" — לוכסן לגיטימי בין שתי מילים
  // נפרדות, לא צורת-מגדר מקוצרת.
  /כן\/לא/,
  // "קו המשווה" = the equator — שם עצם, לא הפועל "משווה".
  /קו המשווה/,
  // סמיכות של "חבר", לא הציווי "חברי" (= לחבר). ראי ההערה בתבנית.
  /חברי (הקבוצה|הכיתה|המשפחה|הצוות|הקהילה|כנסת)/,
];

type Bank = ReadonlyArray<Record<string, unknown>>;
const read = (p: string): Bank => JSON.parse(readFileSync(p, "utf8")) as Bank;

/**
 * 🔴 הסרת ניקוד לפני ההשוואה.
 *
 * `סִפרי` (עם חיריק, U+05B4) הוא **אותו ציווי** כמו `ספרי`, אבל סימן
 * הניקוד יושב בתוך המילה ולכן אף אחת מארבע התבניות אינה נדלקת —
 * השומר עיוור לגמרי. זה לא תרחיש תיאורטי: המילה הזו ישבה במאגר
 * הלוגיקה ועברה ירוק, ובמאגרי הפוניקה כבר יש טקסט מנוקד.
 *
 * באפליקציה שמלמדת קריאה, ניקוד הוא הדבר **הטבעי** לכתוב — ולכן
 * הפער הזה היה נפתח שוב אצל כל מי שיוסיף תוכן מנוקד. הפתרון הוא
 * נרמול, לא עוד ערך ברשימת-המילים.
 */
const stripNiqqud = (s: string): string => s.replace(/[֑-ׇ]/g, "");

/** כל מחרוזת בפריט, פרט ל-parentTip. משטח גם מערכים (`steps`). */
function childFacingStrings(item: Record<string, unknown>): string[] {
  const out: string[] = [];
  for (const [key, value] of Object.entries(item)) {
    if (key === "parentTip") continue;
    if (typeof value === "string") out.push(value);
    else if (Array.isArray(value)) {
      for (const v of value) if (typeof v === "string") out.push(v);
    }
  }
  return out;
}

/**
 * מסונן ל-`.json` — אותו סינון בדיוק כמו בשער-הכיסוי למטה. בלי זה
 * קובץ README או `.gitkeep` בתיקייה היה מפיל את כל ארבע הבדיקות על
 * שגיאת-פרסור, **ובו-זמנית** מבטל את שער-הכיסוי שאמור לתפוס בדיוק
 * את חוסר-ההתאמה הזה.
 */
const enrichmentFiles = readdirSync(ENRICHMENT_DIR)
  .filter((f) => f.endsWith(".json"))
  .map((f) => `${ENRICHMENT_DIR}/${f}`);
const allFiles = [...enrichmentFiles, ...PHONICS];

describe("תוכן — לשון פנייה מנוטרלת (G4)", () => {
  it.each(allFiles)("%s — בלי ציווי בלשון נקבה", (file) => {
    const offenders: string[] = [];
    for (const item of read(file)) {
      for (const s of childFacingStrings(item)) {
        if (LEXICAL_EXEMPT.some((r) => r.test(stripNiqqud(s)))) continue;
        if (FEMININE_IMPERATIVES.test(stripNiqqud(s))) offenders.push(`${item.id}: ${s}`);
      }
    }
    expect(
      offenders,
      `ציווי בלשון נקבה פונה רק לחצי מהמשתמשים. להשתמש בשם-פועל ` +
        `("למלא את הכוס"), לא בהכפלה ולא בלוכסן:\n${offenders.join("\n")}`,
    ).toEqual([]);
  });

  it.each(allFiles)("%s — בלי פנייה בגוף שני נקבה", (file) => {
    const offenders: string[] = [];
    for (const item of read(file)) {
      for (const s of childFacingStrings(item)) {
        if (FEMININE_ADDRESS.test(stripNiqqud(s))) offenders.push(`${item.id}: ${s}`);
      }
    }
    expect(offenders, `פנייה בלשון נקבה:\n${offenders.join("\n")}`).toEqual([]);
  });

  /**
   * נבדק רק ב-`activity` וב-`steps` — שם הנושא הוא **הילד/ה**
   * ("בודקות אם הקרח צף"). בפרוזה של `why`/`expected` הנושא הוא
   * לרוב **דבר** ("כל תרבות מסמנת זמן", "קו המשווה", "ההשוואה
   * מגלה"), ושם אותה צורה תקינה לגמרי. סריקה גורפת הייתה מסמנת
   * עברית תקנית כהפרה — ובדיקה שצועקת על תקין נכבית בסוף.
   */
  it.each(allFiles)("%s — בלי רבים/יחיד-נקבה (מגדר בתחפושת)", (file) => {
    const offenders: string[] = [];
    for (const item of read(file)) {
      const steps = Array.isArray(item.steps) ? (item.steps as unknown[]) : [];
      const scoped: unknown[] = [item.activity, ...steps];
      for (const s of scoped) {
        if (typeof s !== "string") continue;
        if (FEMININE_PLURAL.test(stripNiqqud(s))) offenders.push(`${item.id}: ${s}`);
      }
    }
    expect(
      offenders,
      `"בודקות" נראה מכליל אבל מסגיר מין — זו הטעות שקל ליפול בה ` +
        `כשמנטרלים בעברית:\n${offenders.join("\n")}`,
    ).toEqual([]);
  });

  it.each(allFiles)("%s — בלי צורות לוכסן", (file) => {
    const offenders: string[] = [];
    for (const item of read(file)) {
      for (const s of childFacingStrings(item)) {
        if (SLASH_FORM.test(stripNiqqud(s))) offenders.push(`${item.id}: ${s}`);
      }
    }
    expect(
      offenders,
      `לוכסן אסור: לא נגיש לקוראי מסך, ומקשה על קורא מתחיל בן 7 ` +
        `— בדיוק מה שהאפליקציה באה ללמד:\n${offenders.join("\n")}`,
    ).toEqual([]);
  });
});

/**
 * 🔴 שער-כיסוי. בלעדיו אפשר להוסיף מאגר תוכן חדש ולקבל ירוק על סמך
 * המאגרים הישנים בלבד — הלקח מ-`measurement-holdout-purity` §5,
 * ומ-T7ב שבו השופט דיווח "0 שגיאות" בלי שראה את מאגרי המדידה כלל.
 * הרשימה נקראת מהדיסק, לא כתובה ביד (הלקח מ-BL-022).
 */
describe("שער-כיסוי", () => {
  it("כל מאגרי ההעשרה נסרקים", () => {
    const onDisk = readdirSync(ENRICHMENT_DIR).filter((f) =>
      f.endsWith(".json"),
    );
    const scanned = enrichmentFiles.map((p) => p.split("/").pop());
    expect(scanned.sort()).toEqual(onDisk.sort());
    expect(onDisk.length).toBeGreaterThan(0);
  });
});

/**
 * מאגרי הבנת-הנקרא **אינם** בסקופ, וזו אינה השמטה אלא הגנה:
 * ~75 מופעי לשון-נקבה שם הם **נרטיב על דמויות** ("סבתא של אורי
 * לימדה אותו", "היא יכולה לעוף"), לא פנייה לקורא. החלפה שם הורסת
 * את הסיפור **ושוברת את התשובה הנכונה**, כי השאלות נשאלות *על*
 * הטקסט. הבדיקה נכשלת אם מישהו יסרוק אותם בטעות בשומר הזה.
 */
describe("גבול הסקופ — הבנת הנקרא מחוץ לשומר", () => {
  /**
   * נבדק לפי **התיקיות שנסרקות**, לא לפי איות-הנתיב. הגרסה הקודמת
   * בדקה `not.toMatch(/comprehension/)` — כלומר מאגר-קריאה שייקרא
   * בשם אחר היה נסרק, והנרטיב שלו היה מסומן כהפרה, בזמן שהבדיקה
   * ממשיכה לדווח ירוק.
   */
  const ALLOWED_DIRS = ["src/content/enrichment/", "src/content/english/"];

  it("השומר סורק רק את תיקיות ההעשרה והפוניקה", () => {
    const outside = allFiles.filter(
      (f) => !ALLOWED_DIRS.some((d) => f.startsWith(d)),
    );
    expect(
      outside,
      `קובץ מחוץ לסקופ נסרק. מאגרי הבנת-הנקרא והמדידה מכילים ` +
        `**נרטיב על דמויות** ("סבתא של אורי לימדה אותו"), לא פנייה ` +
        `לקורא — סריקה שלהם מסמנת סיפור תקין כהפרה:\n${outside.join("\n")}`,
    ).toEqual([]);
  });

  it("אף מאגר קריאה או מדידה אינו נסרק", () => {
    const reading = allFiles.filter((f) =>
      /comprehension|measurement|hebrew\//.test(f),
    );
    expect(reading).toEqual([]);
  });
});
