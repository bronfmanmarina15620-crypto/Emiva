const PARENT_DIR = "src/app/parent";
const LIB_DIR = "src/lib";

/**
 * 🔴 **בלי `\b`.** גבול-מילה ב-JS הוא ASCII בלבד ואינו נדלק אחרי אות
 * עברית, ולכן בדיקה שנשענת עליו עוברת תמיד — כלומר מתה. זה הכשל
 * שנתפס ב-BL-021 וחזר בסבב הראשון של שומר-התוכן; נכתב כאן מפורשות.
 */
/**
 * 🔴 `<` ו-`>` **חייבים** להיות כאן. בריפו הזה הצורה הנפוצה ביותר
 * לכתוב טקסט-מסך היא JSX צמוד-לתגית (`<th>שלטה</th>`), ובלי התווים
 * האלה כל שורה כזו היא נקודה עיוורת — הבדיקה ירוקה והמחרוזת חיה.
 * נמצא בסקירה השנייה: 18 שורות כאלה ב-`src/app/parent/**`.
 */
/**
 * ⚠️ הבקטיק נכתב כ-``` ולא כתו גולמי — בתוך template literal הוא
 * סוגר את המחרוזת ומפיל את הקובץ על שגיאת-פרסור. הוא **חייב** להיות
 * גבול: כל מחרוזות שורת-הפעולה בריפו כתובות כ-template literals,
 * ולכן `` `סימנה 😣` `` היה חומק בלעדיו (נמצא בסקירה השנייה).
 */
const B_CHARS = String.raw`\s,.:;!?"״'׳()—–־…“”‘’{}<>` + "`";
const B_START = `(?<=^|[${B_CHARS}])`;
const B_END = `(?=[${B_CHARS}]|$)`;

/**
 * התייחסות לילד בלשון נקבה.
 *
 * 🔴 **זו תבנית, לא רשימת-המחרוזות-שתוקנו.** הסבב הראשון של השומר
 * הזה נכשל בדיוק בזה: תשע החלופות היו **בדיוק תשע המחרוזות שהדיף
 * תיקן**, ולכן הוא דיווח ירוק בזמן ש-7 מחרוזות חיות על המסך
 * (*"איך היה לה השבוע"*, *"שלטה"*, *"של הבנות"*, *"שתיהן"*) —
 * בדיוק דפוס-הכשל שנרשם ב-22.8 ("רשימה מהזיכרון פספסה 30+ צורות").
 * רשימה תופסת את העבר; תבנית תופסת גם את מה שייכתב מחר.
 *
 * הקידומות (`ה`/`ו`/`כ`/`ש`/`ל`/`מ`/`ב`) חלק מהתבנית ולא
 * מגבול-הפתיחה, כי `כשהילדה` הוא מילה אחת.
 */
/**
 * ⚠️ **שתי תבניות, לא אחת — וההפרדה מהותית.**
 *
 * קידומת-אות (`ה`/`כ`/`ש`/`ל`…) מותרת רק ל**שמות-עצם**
 * (`כשהילדה`), ו**אסורה** לכינויים: בלעדיה `לה` נתפס בתוך
 * `להציע`, ו`היא` בתוך `שהיא` — כלומר כל שורת-פעולה תקינה
 * מסומנת כהפרה. שומר שצועק על תקין נכבה בסוף.
 */
const CHILD_NOUNS = String.raw`ילדה|ילדות|בנות|הבת|שתיהן|כולן|לבחירתן`;

/**
 * פעלים בגוף שלישי-נקבה — **מקור אחד**, שמשמש גם את התבנית העצמאית
 * וגם את תבנית-ההקשר שליד שם-הפרופיל. הוספת פועל כאן מחזקת את שתי
 * ההגנות בבת-אחת; שתי רשימות נפרדות היו נפרדות מיד (בסקירה נמצא
 * ש-`סימנה` נוספה ו-`נראית` לא, באותו קובץ במרחק 9 שורות).
 */
const FEM_VERBS = [
  String.raw`שלטה|התחילה|סיימה|התקדמה|ענתה|טעתה|למדה|הצליחה|נתקעה`,
  String.raw`דיווחה|בחרה|קראה|כתבה|פתרה|מתקשה|מרגישה|ישנה|סימנה`,
  // ⚠️ `נרשמה`/`יודעת` **הוסרו במכוון**: הן חלות באותה מידה על
  // נושא-דבר ("**נרשמה** שמחה", "האפליקציה **יודעת** לבד"), ולכן
  // סימנו שורות תקינות. מה שנשאר כאן הוא פעלים שנושאם כמעט תמיד אדם.
  String.raw`נראית|העבירה|ראתה|הבינה|ניסתה|ויתרה`,
  String.raw`צריכה|מבינה|מתקדמת|לומדת`,
  // עתיד נסתרת — "כשתרצה", "אם תצליח". חמק מהסבב הראשון כי חיפשתי
  // עבר והווה בלבד; `parent-history.ts` השתמש ב-`כשתרצה`.
  String.raw`תרצה|כשתרצה|תצליח|תסיים|תתחיל|תבחר|תגיע|תוכל|תדע|תלמד`,
].join("|");

/** כינויים ופעלים — **בלי** קידומת-אות, ראי ההערה למעלה. */
const CHILD_PRONOUNS_VERBS = [
  String.raw`היא|הן|אותה|אותן|שלה|שלהן|עצמה|עצמן|אצלה|אצלן|לה|להן`,
  FEM_VERBS,
  String.raw`שמחות|ישנות|לומדות|קוראות|מתרגלות|מצליחות`,
].join("|");

/**
 * 🔴 **תבנית-הקשר — פועל בגוף שלישי-נקבה סמוך לשם הפרופיל.**
 *
 * הרשימה למעלה תמיד תפגר אחרי העברית: בסקירה נמצא ש-`נראית` חמקה
 * ממנה בזמן ש-`סימנה` נתפסה — **שתיהן באותו קובץ, במרחק 9 שורות**.
 * הסיגנל היציב הוא **מיקום**: מחרוזת שמדברת על הילד חייבת לנקוב
 * בשמו, ולכן הפועל יושב סמוך ל-`${name}`.
 *
 * ⚠️ **למה זו עדיין רשימת-פעלים ולא סיומת מורפולוגית.** ניסיתי
 * לזהות פועל לפי צורתו, וזה **אינו ניתן** בעברית בלי מנתח מורפולוגי:
 * `שמחה` היא גם פועל וגם שם-עצם; `רמה` · `קבוצה` · `תוצאה` · `טובה`
 * כולן נגמרות ב-`ה` ואינן פעלים. תבנית `[א-ת]+ה` סימנה
 * *"${name} ברמה גבוהה"* כהפרה — וזה בדיוק הכיוון שההערה בראש
 * הקובץ מזהירה ממנו: **שומר שצועק על תקין נכבה בסוף.**
 *
 * הפשרה המודעת: `FEM_VERBS` **משותפת** עם `CHILD_PRONOUNS_VERBS`,
 * כך שהוספת פועל שם מחזקת את שתי ההגנות בבת-אחת. מעליה יושבת
 * שכבה שנייה (`CONTEXT_ONLY_VERBS`) לפעלים שרק סמיכות-לשם הופכת
 * לחד-משמעיים — ראי ההערה שלה למטה.
 */
/**
 * ⚠️ **הפיסוק חייב להיות מותר בין השם לפועל.** הגרסה הראשונה
 * הרשתה רק אותיות עבריות בין השניים, ולכן `${p.name} — לא נרשמה`
 * עבר ירוק — כלומר **שתי השורות ב-`foundation.ts` שהתבנית נבנתה
 * בשבילן** יצאו מהישג-ידה ברגע שנוסף להן מקף. הפורמט
 * `שם — תיאור` הוא הרווח בקובץ הזה, ולכן זה לא היה נשאר תיאורטי.
 */
/**
 * פעלים שנבדקים **רק** בסמיכות לשם — לא בתבנית העצמאית.
 *
 * `עברה` היא הפועל המרכזי של דומיין המדידה, ולכן היא דו-שימושית:
 * *"המדידה **עברה**"* ו-`passed: "עברה"` (badge) הם נושא-**דבר**
 * ותקינים, אבל *"${name} **עברה** את הסף"* מדבר על הילד. ההקשר
 * מפריד ביניהם בדיוק: הצורה התקינה אינה מזכירה את שם-הפרופיל.
 *
 * זו נסיגה מכוונת מ"מקור אחד" — הרשימה המשותפת היא ברירת-המחדל
 * הנכונה, וזו שכבה שנייה לפעלים שרק ההקשר הופך אותם לחד-משמעיים.
 *
 * ⚠️ `נרשמה` ו-`שמחה` **אינן** כאן, אף שהן דו-שימושיות גם הן:
 * הן מופיעות בקוד החי בתוך *"${p.name} — לא **נרשמה שמחה** בלמידה"*,
 * שם הפועל מסכים עם **"שמחה"** (שם-עצם) ולא עם הילד. הוספתן סימנה
 * מיד שורה תקינה — כלומר סמיכות-לשם אינה מספיקה בשבילן.
 */
const CONTEXT_ONLY_VERBS = String.raw`עברה`;

const NAME_ADJACENT_FEMININE = new RegExp(
  String.raw`\$\{(?:p\.)?name\}` +
    String.raw`(?:[\s—–,:()"׳'-]|[א-ת]+){0,24}?` +
    String.raw`\s(?:${FEM_VERBS}|${CONTEXT_ONLY_VERBS})` +
    B_END,
);

const CHILD_FEMININE_BASE = new RegExp(
  "(?:" +
    `(?:(?:${B_START}|(?<=[הוכשלמב]))(?:${CHILD_NOUNS}))` +
    "|" +
    `(?:${B_START}(?:${CHILD_PRONOUNS_VERBS}))` +
    ")" +
    B_END,
);

const CHILD_FEMININE = {
  test: (s: string): boolean =>
    CHILD_FEMININE_BASE.test(s) || NAME_ADJACENT_FEMININE.test(s),
};

const SLASH_FORM = new RegExp(String.raw`[א-ת]\/(ה|ית|ות|ים|י)` + B_END);

/**
 * חריגים אמיתיים — פנייה **להורה**, שאינה בסקופ (ראי הכותרת).
 *
 * 🔴 **החריג מוסר מהשורה, ולא מדלג עליה.** הגרסה הראשונה עשתה
 * `return` על כל השורה שהתאימה לחריג — כלומר הפרה אמיתית ש**יושבת
 * באותה שורה** הושתקה יחד איתו (*"— היא תימחק. הילדה תאבד את
 * ההתקדמות"* עבר ירוק). חריג אמור לצמצם את שטח-הבדיקה בדיוק
 * בגודל הביטוי הפטור, לא בגודל השורה.
 */
const PARENT_ADDRESS_EXEMPT = [
  // הבאנר: "אל תפתחי" הוא פנייה להורה; "הילד או הילדה" הוא הניסוח
  // המנוטרל שהחליף את "כשהילדה", ולכן השורה כולה תקינה.
  /אל תפתחי את הדף הזה כשהילד או הילדה ליד המסך\./,

  // 🔴 **נסתרת שמתייחסת ל*דבר*, לא לילד.** בעברית אין ניטרלי, ולכן
  // "ההתקדמות ... **היא** תימחק" ו-"מוחקים **אותה**" הם דקדוק
  // תקין לחלוטין — הנושא הוא קובץ-הגיבוי. סימונם כהפרה היה
  // מלמד שהשומר מרעיש, וזו הדרך שבה שומר נכבה.
  /מוחקים אותה בלי אזהרה/,
  /— היא תימחק/,
  /סביר שהסיבה היא \$\{cause\}/,

  // "לבנות ביטחון" = שם-פועל ("to build"), לא "בנות" (girls).
  /כדי לבנות ביטחון/,
];

function walk(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name).replace(/\\/g, "/");
    if (entry.isDirectory()) out.push(...walk(p));
    else if (/\.tsx?$/.test(entry.name)) out.push(p);
  }
  return out;
}

const parentFiles = walk(PARENT_DIR);

/**
 * 🔴 **הרשימה נגזרת מה-imports, לא נכתבת ביד.**
 *
 * הגרסה הקודמת מנתה **שני** קבצים (`parent-dashboard`, `parent-history`),
 * ולכן ארבע מחרוזות מגודרות חיו על-מסך ועברו ירוק — כולל **תוצאת
 * המבחן החיצוני** (*"הילדה העבירה את הידע"* ב-`measurement.ts`),
 * המסך המשמעותי ביותר באזור ההורה. שער-כיסוי שנשען על רשימה
 * ידנית הוא שער מדומה: הוא מאשר את מה שכבר ברשימה.
 *
 * במקום זה נסרק **כל מודול ש-`src/app/parent/**` מייבא בפועל**.
 * מודול חדש שייובא ייכנס לסריקה מעצמו — זה לקח BL-022, שהשומר
 * כבר מצטט בשער-הכיסוי של `parentFiles`.
 */
function importedLibFiles(): string[] {
  const found = new Set<string>();
  for (const f of parentFiles) {
    const src = readFileSync(f, "utf8");
    for (const m of src.matchAll(/from "@\/lib\/([a-zA-Z0-9-]+)"/g)) {
      const p = `${LIB_DIR}/${m[1]}.ts`;
      if (existsSync(p)) found.add(p);
    }
  }
  return [...found].sort();
}

const libFiles = importedLibFiles();
const allFiles = [...parentFiles, ...libFiles];

/** הסרת ניקוד לפני ההשוואה — הלקח מ-`content-address-form`. */
const stripNiqqud = (s: string): string => s.replace(/[֑-ׇ]/g, "");

/**
 * שורות-הערה מדולגות — הן **אינן נראות למשתמש**.
 *
 * ההערות בקוד הזה מתעדות את הבאג שתוקן, ולכן הן **חייבות** לצטט את
 * הצורות האסורות (*"ולתת לה לבחור"*, *"היא מתקשה"*). שומר שסורק
 * אותן מכריח לכתוב תיעוד עקום כדי לרצות בדיקה — ותיעוד עקום הוא
 * בדיוק מה שגורם לכלל הבא להיכתב לא-נכון.
 *
 * ⚠️ הסינון הוא **שורה שמתחילה** ב-`//` או ב-`*`, ולא "מכילה" —
 * כדי ש-JSX עם הערה בסוף השורה עדיין ייסרק.
 */
const isCommentLine = (line: string): boolean =>
  /^\s*(\/\/|\/?\*)/.test(line);

/**
 * מוחק מהשורה את הביטויים הפטורים בלבד, ומחזיר את השארית לבדיקה.
 *
 * ההחלפה היא ברווח (ולא במחרוזת ריקה) כדי שלא ייווצר צירוף מלאכותי
 * משתי מילים שהיו רחוקות זו מזו לפני המחיקה.
 */
const stripExempt = (s: string): string =>
  PARENT_ADDRESS_EXEMPT.reduce(
    (acc, r) => acc.replace(new RegExp(r.source, "g"), " "),
    s,
  );

describe("מסכי הורה — התייחסות לילד בלי מגדר (G5)", () => {
  it.each(allFiles)("%s — בלי התייחסות לילד בלשון נקבה", (file) => {
    const offenders: string[] = [];
    const lines = readFileSync(file, "utf8").split("\n");
    lines.forEach((line, i) => {
      if (isCommentLine(line)) return;
      const clean = stripExempt(stripNiqqud(line));
      if (CHILD_FEMININE.test(clean)) offenders.push(`${i + 1}: ${line.trim()}`);
    });
    expect(
      offenders,
      `מסך ההורה מדבר על הילד בלשון נקבה — הורה של בן רואה טקסט ` +
        `שמדבר על בת. לנטרל ("ולתת לבחור", "אם יש קושי"), לא להפוך ` +
        `לזכר ולא ללוכסן.\n⚠️ פנייה **להורה** ("את יכולה") מותרת ` +
        `ואינה בסקופ:\n${offenders.join("\n")}`,
    ).toEqual([]);
  });

  it.each(allFiles)("%s — בלי צורות לוכסן", (file) => {
    const offenders: string[] = [];
    const lines = readFileSync(file, "utf8").split("\n");
    lines.forEach((line, i) => {
      // הערות מדולגות כמו בבדיקה למעלה — התיעוד בקוד **חייב** לצטט
      // את הצורה האסורה ("מוכן/ה") כדי להסביר למה היא אסורה.
      if (isCommentLine(line)) return;
      if (SLASH_FORM.test(stripNiqqud(line)))
        offenders.push(`${i + 1}: ${line.trim()}`);
    });
    expect(
      offenders,
      `לוכסן אסור: לא נגיש לקוראי מסך (תקן gov.il), ומקשה על קורא ` +
        `מתחיל בן 7 — בדיוק מה שהאפליקציה באה ללמד:\n${offenders.join("\n")}`,
    ).toEqual([]);
  });
});

/**
 * 🔴 שער-כיסוי. בלעדיו אפשר להוסיף מסך-הורה חדש ולקבל ירוק על סמך
 * המסכים הישנים בלבד — הלקח מ-`measurement-holdout-purity` §5.
 * הרשימה נקראת מהדיסק, לא כתובה ביד (הלקח מ-BL-022).
 */
describe("שער-כיסוי", () => {
  it("כל מסכי ההורה נסרקים", () => {
    expect(parentFiles.length).toBeGreaterThan(0);
    for (const f of parentFiles) expect(f.startsWith(PARENT_DIR)).toBe(true);
  });

  /**
   * 🔴 הבדיקה הקודמת רק ודאה שהקבצים **קריאים** — כלומר היא עברה
   * ירוק על רשימה בת שני קבצים בזמן שארבע מחרוזות מגודרות חיו
   * במודולים שלא נסרקו. שער-כיסוי חייב לאמת את **הגזירה**, לא את
   * הרשימה: שהמודולים שמסכי-ההורה מייבאים בפועל אכן נכנסו.
   */
  it("כל מודול lib שמסכי ההורה מייבאים — נסרק", () => {
    const imported = new Set<string>();
    for (const f of parentFiles) {
      const src = readFileSync(f, "utf8");
      for (const m of src.matchAll(/from "@\/lib\/([a-zA-Z0-9-]+)"/g)) {
        const p = `${LIB_DIR}/${m[1]}.ts`;
        if (existsSync(p)) imported.add(p);
      }
    }
    expect(imported.size).toBeGreaterThan(0);
    const missing = [...imported].filter((p) => !allFiles.includes(p));
    expect(
      missing,
      `מודול שמסך-הורה מייבא אינו נסרק. כך בדיוק ארבע מחרוזות ` +
        `מגודרות שרדו — כולל תוצאת המבחן החיצוני:\n${missing.join("\n")}`,
    ).toEqual([]);
  });

  /**
   * הגזירה חייבת לתפוס גם את `parent-*.ts` — אם מסך מפסיק לייבא
   * אחד מהם, הכיסוי מצטמצם בשקט. הבדיקה מקבעת את הרצפה.
   */
  it("שכבת ה-parent-* נסרקת", () => {
    for (const f of ["parent-dashboard", "parent-history"]) {
      expect(libFiles).toContain(`${LIB_DIR}/${f}.ts`);
    }
  });
});

