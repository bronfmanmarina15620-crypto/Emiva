#!/usr/bin/env bash
# שוטר: עוצר פקודות הרסניות ודורש אישור מפורש של מרינה.
#
# רץ לפני כל פקודת Bash/PowerShell שקלוד מנסה להריץ (PreToolUse).
# exit 0 = מותר לעבור. exit 2 = חסום, קלוד מקבל את ההודעה.
#
# זו נעילה, לא בקשה — קלוד לא יכול לעקוף אותה, לשכוח אותה,
# או להחליט שהמקרה "טריוויאלי".

input=$(cat)

# שולף את הפקודה מתוך ה-JSON שהמערכת שולחת
cmd=$(printf '%s' "$input" | grep -o '"command"[[:space:]]*:[[:space:]]*"\(\\.\|[^"\\]\)*"' | head -1)

block() {
  echo "🔒 חסום: $1" >&2
  echo "" >&2
  echo "זו פקודה הרסנית. מרינה חייבת לאשר אותה במפורש לפני הרצה." >&2
  echo "הסבר לה מה הפקודה תעשה, ובקש אישור מילולי." >&2
  exit 2
}

# 1. מחיקת קבצים
case "$cmd" in
  *"rm -rf"*|*"rm -r "*|*"rm -f"*|*"Remove-Item"*|*" del "*|*"rmdir"*)
    block "מחיקת קבצים" ;;
esac

# 2. מחיקת עבודה בגיט
case "$cmd" in
  *"reset --hard"*|*"clean -fd"*|*"checkout -- "*|*"restore ."*)
    block "מחיקת שינויים בגיט" ;;
esac

# 3. (הוסר 2026-07-22) חסימת git push — הריפו הפך לפרטי, החשש מחשיפה פומבית
#    כבר לא תקף. שכתוב היסטוריה (push --force) עדיין נחסם למטה.

# 4. שכתוב היסטוריה
case "$cmd" in
  *"push --force"*|*"push -f"*|*"filter-branch"*|*"rebase"*)
    block "שכתוב היסטוריית גיט" ;;
esac

exit 0
