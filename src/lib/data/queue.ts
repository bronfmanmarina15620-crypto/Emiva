const chains = new Map<string, Promise<unknown>>();

/**
 * מריץ `job` בתור של `key` — אחרי כל מה שכבר ממתין לאותו מפתח.
 *
 * הכישלון של `job` אינו שובר את התור: השרשרת ממשיכה לעבודה הבאה,
 * והשגיאה חוזרת רק לקורא שלה.
 *
 * 🔴 **`key` חייב להיות מפתח-האחסון עצמו — לא מזהה-ישות.**
 * ההגנה היא פר-מפתח, ולכן שתי עבודות על מפתחות שונים רצות
 * במקביל. `profiles.ts` שומר את **כל** הפרופילים במפתח יחיד
 * (`emiva.profiles.v1`), ולכן `withKeyLock(profile.id, ...)` —
 * הצורה האינטואיטיבית — נותן ירוק **ומאבד פרופיל**: שתי
 * עבודות עם מזהים שונים ייגעו באותו מפתח בלי תיאום.
 * הצורה הנכונה שם היא `withKeyLock("emiva.profiles.v1", ...)`.
 * (נמצא בסקירה 22.8, לפני שהקוראים הועברו.)
 */
export function withKeyLock<T>(key: string, job: () => Promise<T>): Promise<T> {
  const prev = chains.get(key) ?? Promise.resolve();
  // `catch` לפני ההמשך: כישלון של עבודה קודמת לא מפיל את הבאות.
  const run = prev.then(
    () => job(),
    () => job(),
  );
  // השרשרת השמורה בולעת שגיאות במכוון — אחרת כל ממתין הבא
  // היה מקבל את השגיאה של מי שלפניו.
  const tail = run.catch(() => undefined).then(() => {
    // 🔴 ניקוי: בלי זה ה-Map גדל לכל מפתח שנכתב אי-פעם ואינו
    // מתרוקן לעולם — דליפה שקטה בדף שנשאר פתוח שעה. מוחקים רק
    // אם אנחנו האחרונים בתור; אחרת מישהו כבר ממתין ואסור לאבד
    // את החוליה.
    if (chains.get(key) === tail) chains.delete(key);
  });
  chains.set(key, tail);
  return run;
}

/** מספר המפתחות הפעילים בתור. לבדיקות ולניטור. */
export function queueSize(): number {
  return chains.size;
}

/**
 * ממתין לניקוז כל התורים. לבדיקות, ולכיבוי מסודר ב-P2.
 *
 * ⚠️ **בלי `chains.clear()`** (נמצא בסקירה 22.8): הניקוי המוקדם
 * שחרר את השרשרות בזמן שעבודות עוד רצו, וכתיבה חדשה שנכנסה תוך
 * כדי הניקוז ראתה תור ריק ורצה **לפני** מי שקדמה לה — כלומר
 * המודול פתח בעצמו בדיוק את המרוץ שהוא נבנה למנוע. הניקוי
 * ממילא קורה לבד ב-`withKeyLock` כשעבודה מסתיימת.
 */
export async function drainQueues(): Promise<void> {
  // לולאה ולא המתנה אחת: עבודה שממתינה יכולה להוסיף עבודה חדשה.
  // כל סיבוב ממתין לצילום-מצב הנוכחי; כשהמפה מתרוקנת — סיימנו.
  // (`withKeyLock` מוחק מפתח כשהעבודה האחרונה עליו נגמרה.)
  let guard = 0;
  while (chains.size > 0 && guard++ < 1000) {
    await Promise.allSettled([...chains.values()]);
  }
}

/** מאפס מצב בין בדיקות. */
export function __resetQueues(): void {
  chains.clear();
}
