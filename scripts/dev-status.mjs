// BL-002 — מראה אילו שרתי-פיתוח רצים כרגע. **קריאה בלבד, לא סוגר כלום.**
//
// הרקע (2026-08-10): נמצאו ארבעה שרתי-פיתוח חיים בו-זמנית, אחד מהם
// יתום מסשן קודם. שרת יתום מחזיק פורט, כותב ל-`.next` ומתנגש עם השרת
// שבאמת עובדים איתו — וזה חלק מהסיבה לשבירות. עד היום הדרך היחידה
// לדעת שזה קורה הייתה להריץ חקירה ידנית.
//
// למה פקודה נפרדת ולא רק חלק מ-`dev:restart`: `dev:restart` **סוגר**.
// כשרוצים רק להסתכל — למשל לפני בנייה, או כשמשהו מרגיש מוזר — פקודה
// שיש לה תופעות-לוואי היא הדבר הלא נכון להריץ.

import { findDevServerPids } from "./lib/find-dev-servers.mjs";

const { pids, detectionFailed } = findDevServerPids();

if (detectionFailed) {
  console.log("⚠️  לא הצלחתי לבדוק. נסי להריץ שוב.");
  process.exit(0);
}

if (pids.length === 0) {
  console.log("✅ אין שרת פיתוח שרץ כרגע.");
} else if (pids.length === 1) {
  console.log(`🟢 רץ שרת פיתוח אחד (PID: ${pids[0]}).`);
} else {
  console.log(
    [
      `🟡 רצים ${pids.length} שרתי פיתוח (PID: ${pids.join(", ")}).`,
      "",
      "יותר מאחד זה כמעט תמיד שרתים יתומים מסשנים קודמים. הם מחזיקים",
      "פורטים וכותבים לאותה תיקייה, וזה גורם לשבירות.",
      "",
      "מה לעשות:  npm run dev:restart  — סוגר את כולם ומעלה אחד נקי.",
    ].join("\n"),
  );
}
