// Next.js (`global-error.js`, `__webpack_modules__ is not a function`)
// ולא על קוד הפרויקט, ולכן קל לבזבז עליהן זמן חיפוש.
//
// **תיקון האבחנה (2026-08-10, אחרי שחזור מבוקר):** ההנחה שהמטמון
// שעל-הדיסק מתקלקל הייתה **שגויה**. השחזור הראה:
//   1. Turbopack נופל *בדיוק* באותה שגיאה — זה לא באג של webpack.
//   2. השרת **לא מתאושש** גם אחרי שהקבצים שגרמו לזה הוסרו.
//   3. הפעלה מחדש **בלי לנקות כלום** (136MB של .next נשארו במקום)
//      החזירה את הכל לתקין.
// כלומר הבעיה היא **מצב בזיכרון של התהליך החי**, לא קבצים מקולקלים.
// מחיקת `.next` "עבדה" רק כי היא כפתה הפעלה מחדש — תופעת-לוואי, לא סיבה.
//
// לכן הפקודה המומלצת היא `npm run dev:restart` (מהיר, שומר על המטמון).
// הסקריפט הזה נשאר כפתרון-גיבוי למקרה נדיר של מטמון שבאמת נפגם
// (למשל דיסק מלא או הפסקת-חשמל באמצע כתיבה).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const cacheDir = path.join(root, ".next");

if (fs.existsSync(cacheDir)) {
  fs.rmSync(cacheDir, { recursive: true, force: true });
  console.log("🧹 מטמון הבנייה נוקה (.next)");
} else {
  console.log("🧹 אין מטמון לנקות");
}
